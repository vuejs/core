import { isArray } from '@vue/shared'
import type { ContextualRenderFn } from '../componentRenderContext'
import type { VNode } from '../vnode'

// #6651 res can be undefined in SSR in string push mode
type SSRSlot = (...args: any[]) => VNode[] | undefined

interface CompiledSlotDescriptor {
  name: string
  fn: SSRSlot
  key?: string
}

/**
 * Compiler runtime helper for creating dynamic slots object
 * @private
 */
export function createSlots(
  slots: Record<string, SSRSlot>,
  dynamicSlots: (
    CompiledSlotDescriptor | CompiledSlotDescriptor[] | undefined
  )[],
): Record<string, SSRSlot> {
  for (let i = 0; i < dynamicSlots.length; i++) {
    const slot = dynamicSlots[i]
    // array of dynamic slot generated by <template v-for="..." #[...]>
    if (isArray(slot)) {
      for (let j = 0; j < slot.length; j++) {
        slots[slot[j].name] = slot[j].fn
      }
    } else if (slot) {
      // conditional single slot generated by <template v-if="..." #foo>
      if (slot.key) {
        const fn = (...args: any[]) => {
          const res = slot.fn(...args)
          // attach branch key so each conditional branch is considered a
          // different fragment
          if (res) (res as any).key = slot.key
          return res
        }
        // the wrapped compiled slot is already normalized. Without this mark,
        // slots handed on in a new object, e.g. `h(Comp, null, { ...slots })`,
        // are normalized again, which turns the `undefined` returned in SSR
        // push mode into a vnode array and drops the pushed content.
        ;(fn as ContextualRenderFn)._n = true
        slots[slot.name] = fn
      } else {
        slots[slot.name] = slot.fn
      }
    }
  }
  return slots
}
