export type RawProps = Record<string, unknown> & {
  // generated by compiler for :[key]="x" or v-bind="x"
  $?: DynamicPropsSource[] & { [interopKey]?: boolean }
}

export type DynamicPropsSource =
  | (() => Record<string, unknown>)
  | Record<string, unknown>

export function isolatePropSources(rawProps: RawProps): RawProps {
  // Static values cannot change while cached and need no commit boundary.
  let hasFunctionSource = false
  for (const key in rawProps) {
    if (key !== '$' && isFunction(rawProps[key])) hasFunctionSource = true
  }
  const dynamicSources = rawProps.$
  if (dynamicSources && !hasFunctionSource) {
    for (let i = 0; i < dynamicSources.length; i++) {
      const source = dynamicSources[i]
      if (isFunction(source)) {
        hasFunctionSource = true
        break
      } else {
        for (const key in source) {
          if (isFunction(source[key])) {
            hasFunctionSource = true
            break
          }
        }
        if (hasFunctionSource) break
      }
    }
  }
  if (!hasFunctionSource) return rawProps

  const isolated: RawProps = Object.create(null)
  let committed: Record<string, unknown> | undefined
  for (const key in rawProps) {
    if (key === '$') continue
    const source = rawProps[key]
    if (isFunction(source)) {
      const target =
        committed || (committed = shallowReactive<Record<string, unknown>>({}))
      isolated[key] = () => target[key]
    } else {
      isolated[key] = source
    }
  }

  let committedDynamicSources:
    | (Record<string, unknown> | undefined)[]
    | undefined
  let previousDynamicSources: Record<string, unknown>[] | undefined
  if (dynamicSources) {
    const isolatedDynamicSources: DynamicPropsSource[] & {
      [interopKey]?: boolean
    } = []
    committedDynamicSources = []
    previousDynamicSources = []
    for (let i = 0; i < dynamicSources.length; i++) {
      const source = dynamicSources[i]
      if (isFunction(source)) {
        const target = (committedDynamicSources[i] = shallowReactive<
          Record<string, unknown>
        >({}))
        previousDynamicSources[i] = {}
        isolatedDynamicSources[i] = () => target
      } else {
        const isolatedSource: Record<string, unknown> = Object.create(null)
        let target: Record<string, unknown> | undefined
        for (const key in source) {
          const value = source[key]
          if (isFunction(value)) {
            if (!target) {
              target = committedDynamicSources[i] = shallowReactive<
                Record<string, unknown>
              >({})
            }
            const committedSource = target
            isolatedSource[key] = () => committedSource[key]
          } else {
            isolatedSource[key] = value
          }
        }
        isolatedDynamicSources[i] = target ? isolatedSource : source
      }
    }
    const symbols = Object.getOwnPropertySymbols(dynamicSources)
    for (let i = 0; i < symbols.length; i++) {
      ;(isolatedDynamicSources as any)[symbols[i]] = (dynamicSources as any)[
        symbols[i]
      ]
    }
    isolated.$ = isolatedDynamicSources
  }

  // Each source keeps its original position and key spelling so prop/attr
  // precedence is unchanged. The writer belongs to the cached component's
  // KeepAlive input scope, so deactivation pauses parent updates without
  // pausing the component.
  // Source invalidations while this effect is paused still leave it dirty.
  // Resuming the input scope therefore schedules one commit with the
  // latest raw props, while an unchanged cache entry needs no work on activation.
  renderEffect(() => {
    if (committed) {
      for (const key in rawProps) {
        if (key !== '$' && isFunction(rawProps[key])) {
          committed[key] = resolveSource(rawProps[key])
        }
      }
    }
    if (dynamicSources) {
      for (let i = 0; i < dynamicSources.length; i++) {
        const source = dynamicSources[i]
        const target = committedDynamicSources![i]
        if (!target) continue
        if (isFunction(source)) {
          const next = resolveFunctionSource(source) || EMPTY_OBJ
          const previous = previousDynamicSources![i]
          for (const key in previous) {
            if (!hasOwn(next, key)) {
              delete target[key]
              delete previous[key]
            }
          }
          for (const key in next) {
            target[key] = previous[key] = next[key]
          }
        } else {
          for (const key in source) {
            if (isFunction(source[key])) {
              target[key] = resolveSource(source[key])
            }
          }
        }
      }
    }
  }, true)
  return isolated
}

export function resolveSource<T>(source: T | (() => T)): T {
  return isFunction(source) ? resolveFunctionSource(source as () => T) : source
}

export function resolveFunctionSource<T>(
  source: (() => T) & { _cache?: ComputedRef<T> },
): T {
  // use existing cache if available
  if (source._cache) {
    return source._cache.value
  }

  // source function is defined in the parent component, so it should be
  // executed in the parent's context. currentInstance is the child component
  // (the one accessing props/slots), so we use parent to get the component
  // where source was defined.
  const parent = currentInstance && currentInstance.parent
  if (parent) {
    // execute the source in the parent's context, but collect its cache in the
    // active consumer scope
    const prev = setCurrentInstance(parent, getCurrentScope())
    try {
      source._cache = computed(oldValue => {
        const prevInner = setCurrentInstance(parent)
        try {
          return stabilizeDynamicSourceValue(oldValue, source())
        } finally {
          restoreCurrentInstance(prevInner)
        }
      })
      onScopeDispose(() => (source._cache = undefined))
    } finally {
      restoreCurrentInstance(prev)
    }
    return source._cache.value
  }

  // no parent, no cache - just call directly
  return source()
}

export function snapshotRawProps(rawProps: RawProps): RawProps {
  // Freeze the parent-provided raw source, not the child props proxy. This
  // keeps prop defaults lazy while preserving v-once input semantics.
  const snapshot: RawProps = Object.create(null)
  for (const key in rawProps) {
    if (key !== '$') {
      const value = resolveSource(rawProps[key])
      snapshot[key] = () => value
    }
  }

  const dynamicSources = rawProps.$
  if (dynamicSources) {
    const snapshotSources: DynamicPropsSource[] & {
      [interopKey]?: boolean
    } = []
    for (let i = 0; i < dynamicSources.length; i++) {
      const source = dynamicSources[i]
      const value: Record<string, unknown> = Object.create(null)
      if (isFunction(source)) {
        const resolved = resolveFunctionSource(
          source as () => Record<string, unknown>,
        )
        for (const key in resolved) {
          value[key] = resolved[key]
        }
        snapshotSources[i] = () => value
      } else {
        for (const key in source) {
          const resolved = resolveSource(source[key])
          value[key] = () => resolved
        }
        snapshotSources[i] = value
      }
    }
    const symbols = Object.getOwnPropertySymbols(dynamicSources)
    for (let i = 0; i < symbols.length; i++) {
      ;(snapshotSources as any)[symbols[i]] = (dynamicSources as any)[
        symbols[i]
      ]
    }
    snapshot.$ = snapshotSources
  }

  return snapshot
}

function stabilizeDynamicSourceValue<T>(oldValue: T | undefined, value: T): T {
  if (!isPlainObject(oldValue) || !isPlainObject(value)) {
    return value
  }

  // Dynamic sources often allocate a fresh object even when the resolved
  // props/attrs are unchanged. Keep the previous identity in that case so
  // computed consumers do not trigger child updates for equivalent values.
  const oldKeys = Object.keys(oldValue)
  const newKeys = Object.keys(value)
  if (oldKeys.length !== newKeys.length) {
    return value
  }

  for (let i = 0; i < newKeys.length; i++) {
    const key = newKeys[i]
    if (
      !hasOwn(oldValue, key) ||
      !Object.is((oldValue as any)[key], (value as any)[key])
    ) {
      return value
    }
  }

  return oldValue
}

export function getPropsProxyHandlers(
  comp: VaporComponent,
): [
  ProxyHandler<VaporComponentInstance> | null,
  ProxyHandler<VaporComponentInstance>,
] {
  if (comp.__propsHandlers) {
    return comp.__propsHandlers
  }
  const propsOptions = normalizePropsOptions(comp)[0]
  const emitsOptions = normalizeEmitsOptions(comp)
  const isProp = (
    propsOptions
      ? (key: string | symbol) =>
          isString(key) && hasOwn(propsOptions, camelize(key))
      : NO
  ) as (key: string | symbol) => key is string
  const isAttr =
    propsOptions || emitsOptions
      ? (key: string | symbol) =>
          isString(key) &&
          key !== '$' &&
          !isProp(key) &&
          !isEmitListener(emitsOptions, key)
      : (key: string | symbol) => isString(key)

  // vdom normalizes class and style on the vnode, so prop resolution already
  // receives normalized values. Match that order here.
  const normalizeRawProp = (key: string, value: unknown) => {
    if (!value) return value
    if (key === 'class' && !isString(value)) return normalizeClass(value)
    if (key === 'style' && isObject(value)) return normalizeStyle(value)
    return value
  }

  const getProp = (instance: VaporComponentInstance, key: string | symbol) => {
    // this enables direct watching of props and prevents `Invalid watch source` DEV warnings.
    if (key === ReactiveFlags.IS_REACTIVE) return true

    if (!isProp(key)) return
    const rawProps = instance.rawProps
    const dynamicSources = rawProps.$
    if (dynamicSources) {
      let i = dynamicSources.length
      let source, isDynamic, rawKey
      while (i--) {
        source = dynamicSources[i]
        isDynamic = isFunction(source)
        source = isDynamic
          ? (resolveFunctionSource(
              source as () => Record<string, unknown>,
            ) as any)
          : source
        for (rawKey in source) {
          if (camelize(rawKey) === key) {
            return resolvePropValue(
              propsOptions!,
              key,
              normalizeRawProp(
                key,
                isDynamic ? source[rawKey] : resolveSource(source[rawKey]),
              ),
              instance,
              resolveDefault,
            )
          }
        }
      }
    }
    for (const rawKey in rawProps) {
      if (camelize(rawKey) === key) {
        return resolvePropValue(
          propsOptions!,
          key,
          normalizeRawProp(key, resolveSource(rawProps[rawKey])),
          instance,
          resolveDefault,
        )
      }
    }
    return resolvePropValue(
      propsOptions!,
      key,
      undefined,
      instance,
      resolveDefault,
      true,
    )
  }

  const withOnceCache = <
    T extends (instance: VaporComponentInstance, key: string | symbol) => any,
  >(
    getter: T,
  ): T => {
    return ((instance: VaporComponentInstance, key: string | symbol) => {
      const cache =
        instance.oncePropsCache ||
        (instance.oncePropsCache = Object.create(null))
      if (!hasOwn(cache, key)) {
        pauseTracking()
        try {
          cache[key] = getter(instance, key)
        } finally {
          resetTracking()
        }
      }
      return cache[key]
    }) as T
  }

  const getOnceProp = withOnceCache(getProp)
  const getMaybeOnceProp = (
    instance: VaporComponentInstance,
    key: string | symbol,
  ) => (instance.isOnce ? getOnceProp : getProp)(instance, key)
  const propsHandlers = propsOptions
    ? ({
        get: getMaybeOnceProp,
        has: (_, key) => isProp(key),
        ownKeys: () => Object.keys(propsOptions),
        getOwnPropertyDescriptor(target, key) {
          if (isProp(key)) {
            return {
              configurable: true,
              enumerable: true,
              get: () => getMaybeOnceProp(target, key),
            }
          }
        },
      } satisfies ProxyHandler<VaporComponentInstance>)
    : null

  if (__DEV__ && propsOptions) {
    Object.assign(propsHandlers!, {
      set: propsSetDevTrap,
      deleteProperty: propsDeleteDevTrap,
    })
  }

  const getAttr = (target: RawProps, key: string | symbol) => {
    if (isString(key) && !isProp(key) && !isEmitListener(emitsOptions, key)) {
      return getAttrFromRawProps(target, key)
    }
  }

  const hasAttr = (target: RawProps, key: string | symbol) => {
    if (isAttr(key)) {
      return hasAttrFromRawProps(target, key)
    } else {
      return false
    }
  }

  const getOnceAttr = withOnceCache((instance, key) =>
    getAttr(instance.rawProps, key),
  )
  const onceAttrKeys = Symbol()
  const getAttrKeys = (target: VaporComponentInstance) =>
    getKeysFromRawProps(target.rawProps).filter(isAttr)
  const getOnceAttrKeys = (target: VaporComponentInstance) => {
    const cache =
      target.oncePropsCache || (target.oncePropsCache = Object.create(null))
    if (!hasOwn(cache, onceAttrKeys)) {
      pauseTracking()
      try {
        // Freeze both the attr key set and its initial values so direct
        // delayed reads do not see attrs added after the once boundary.
        const keys = getAttrKeys(target)
        cache[onceAttrKeys] = keys
        for (let i = 0; i < keys.length; i++) {
          const key = keys[i]
          if (!hasOwn(cache, key)) {
            cache[key] = getAttr(target.rawProps, key)
          }
        }
      } finally {
        resetTracking()
      }
    }
    return cache[onceAttrKeys] as string[]
  }
  const getMaybeOnceAttrKeys = (target: VaporComponentInstance) =>
    target.isOnce ? getOnceAttrKeys(target) : getAttrKeys(target)
  const getMaybeOnceAttr = (
    instance: VaporComponentInstance,
    key: string | symbol,
  ) =>
    instance.isOnce
      ? getOnceAttrKeys(instance).includes(key as string)
        ? getOnceAttr(instance, key)
        : undefined
      : getAttr(instance.rawProps, key)
  const attrsHandlers = {
    get: getMaybeOnceAttr,
    has: (target, key: string | symbol) =>
      target.isOnce
        ? getOnceAttrKeys(target).includes(key as string)
        : hasAttr(target.rawProps, key),
    ownKeys: getMaybeOnceAttrKeys,
    getOwnPropertyDescriptor(target, key: string | symbol) {
      if (
        isString(key) &&
        (target.isOnce
          ? getOnceAttrKeys(target).includes(key)
          : hasAttr(target.rawProps, key))
      ) {
        return {
          configurable: true,
          enumerable: true,
          get: () => getMaybeOnceAttr(target, key),
        }
      }
    },
  } satisfies ProxyHandler<VaporComponentInstance>

  if (__DEV__) {
    Object.assign(attrsHandlers, {
      set: propsSetDevTrap,
      deleteProperty: propsDeleteDevTrap,
    })
  }

  return (comp.__propsHandlers = [propsHandlers, attrsHandlers])
}

export function getAttrFromRawProps(rawProps: RawProps, key: string): unknown {
  if (key === '$') return
  // need special merging behavior for class & style
  const merged = key === 'class' || key === 'style' ? ([] as any[]) : undefined
  const dynamicSources = rawProps.$
  if (dynamicSources) {
    let i = dynamicSources.length
    let source, isDynamic
    while (i--) {
      source = dynamicSources[i]
      isDynamic = isFunction(source)
      source = isDynamic
        ? resolveFunctionSource(source as () => Record<string, unknown>)
        : source
      if (source && hasOwn(source, key)) {
        const value = isDynamic ? source[key] : resolveSource(source[key])
        if (merged) {
          merged.push(value)
        } else {
          return value
        }
      }
    }
  }
  if (hasOwn(rawProps, key)) {
    const value = resolveSource(rawProps[key])
    if (merged) {
      merged.push(value)
    } else {
      return value
    }
  }
  if (merged && merged.length) {
    return merged
  }
}

export function hasAttrFromRawProps(rawProps: RawProps, key: string): boolean {
  if (key === '$') return false
  const dynamicSources = rawProps.$
  if (dynamicSources) {
    let i = dynamicSources.length
    while (i--) {
      const source = resolveSource(dynamicSources[i])
      if (source && hasOwn(source, key)) {
        return true
      }
    }
  }
  return hasOwn(rawProps, key)
}

export function getKeysFromRawProps(rawProps: RawProps): string[] {
  const keys: string[] = []
  for (const key in rawProps) {
    if (key !== '$') keys.push(key)
  }
  const dynamicSources = rawProps.$
  if (dynamicSources) {
    let i = dynamicSources.length
    let source
    while (i--) {
      source = isFunction(dynamicSources[i])
        ? resolveFunctionSource(
            dynamicSources[i] as () => Record<string, unknown>,
          )
        : dynamicSources[i]
      for (const key in source) {
        keys.push(key)
      }
    }
  }
  return Array.from(new Set(keys))
}

export function normalizePropsOptions(
  comp: VaporComponent,
): NormalizedPropsOptions {
  const cached = comp.__propsOptions
  if (cached) return cached

  const raw = comp.props
  if (!raw) return EMPTY_ARR as []

  const normalized: NormalizedPropsOptions[0] = {}
  const needCastKeys: NormalizedPropsOptions[1] = []
  baseNormalizePropsOptions(raw, normalized, needCastKeys)

  return (comp.__propsOptions = [normalized, needCastKeys])
}

function resolveDefault(
  factory: (props: Record<string, any>) => unknown,
  instance: VaporComponentInstance,
) {
  const prev = setCurrentInstance(instance)
  const res = factory.call(null, instance.props)
  restoreCurrentInstance(prev)
  return res
}

export function hasFallthroughAttrs(
  comp: VaporComponent,
  rawProps: RawProps | null | undefined,
): boolean {
  if (rawProps) {
    // dynamic sources can produce attrs keys at any time
    if (rawProps.$) {
      return true
    }
    // otherwise fallthrough potential requires an undeclared static key —
    // static keys are fixed at creation, so an empty rawProps can never
    // produce attrs later
    const propsOptions = comp.props ? normalizePropsOptions(comp)[0]! : null
    for (const key in rawProps) {
      if (!propsOptions || !hasOwn(propsOptions, camelize(key))) {
        return true
      }
    }
  }
  return false
}

/**
 * dev only
 */
export function setupPropsValidation(
  instance: VaporComponentInstance,
  warningContext: GenericComponentInstance | VNode = instance,
): void {
  const rawProps = instance.rawProps
  if (!rawProps) return
  renderEffect(() => {
    pushWarningContext(warningContext)
    validateProps(
      resolveDynamicProps(rawProps),
      instance.props,
      normalizePropsOptions(instance.type)[0]!,
    )
    popWarningContext()
  }, true /* noLifecycle */)
}

export function resolveDynamicProps(props: RawProps): Record<string, unknown> {
  const mergedRawProps: Record<string, any> = {}
  for (const key in props) {
    if (key !== '$') {
      mergedRawProps[key] = resolveSource(props[key])
    }
  }
  if (props.$) {
    for (const source of props.$) {
      const isDynamic = isFunction(source)
      const resolved = isDynamic ? resolveFunctionSource(source) : source
      for (const key in resolved) {
        const value = isDynamic ? resolved[key] : resolveSource(source[key])
        if (key === 'class' || key === 'style') {
          const existing = mergedRawProps[key]
          if (isArray(existing)) {
            existing.push(value)
          } else {
            mergedRawProps[key] = [existing, value]
          }
        } else {
          mergedRawProps[key] = value
        }
      }
    }
  }
  return mergedRawProps
}

function propsSetDevTrap(_: any, key: string | symbol) {
  warn(
    `Attempt to mutate prop ${JSON.stringify(key)} failed. Props are readonly.`,
  )
  return true
}

function propsDeleteDevTrap(_: any, key: string | symbol) {
  warn(
    `Attempt to delete prop ${JSON.stringify(key)} failed. Props are readonly.`,
  )
  return true
}

export const rawPropsProxyHandlers: ProxyHandler<RawProps> = {
  get: getAttrFromRawProps,
  has: hasAttrFromRawProps,
  ownKeys: getKeysFromRawProps,
  getOwnPropertyDescriptor(target, key: string) {
    if (hasAttrFromRawProps(target, key)) {
      return {
        configurable: true,
        enumerable: true,
        get: () => getAttrFromRawProps(target, key),
      }
    }
  },
}
